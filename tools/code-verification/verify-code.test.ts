/**
 * Executes every code example in the course-material packages and compares stdout with the
 * documented expected output (Professional Programming Education Standard, Part L).
 *
 *   npm run verify:code
 *
 * - runtime 'lua54' → official Lua 5.4 C interpreter via the `lupa` Python package
 *                      (pip install lupa); runner: tools/code-verification/run-lua54.py
 * - runtime 'luau'  → official Luau VM via tools/luau-runner (cargo build; see its README);
 *                      override the binary with LUAU_RUNNER=/path/to/luau-runner
 * - runtime 'roblox'→ NOT executed (Roblox Studio only) — reported as such, never claimed.
 *
 * Writes docs/CODE-VERIFICATION.md with the result of every example.
 */
import { spawnSync } from 'node:child_process';
import { existsSync, mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { describe, expect, it } from 'vitest';
import { collectCodeExamples } from '@/db/content/validate';
import { CONTENT_PACKAGES } from '@/content';

const ROOT = resolve(__dirname, '../..');
const LUAU_RUNNER = process.env.LUAU_RUNNER ?? join(ROOT, 'tools/luau-runner/target/release/luau-runner');
const LUA_RUNNER = join(ROOT, 'tools/code-verification/run-lua54.py');

type Result = { where: string; id: string; runtime: string; status: 'passed' | 'failed' | 'not-executed' | 'tool-missing'; detail?: string };

function haveLua54() {
  return spawnSync('python3', ['-c', 'import lupa.lua54'], { encoding: 'utf-8' }).status === 0;
}

function run(runtime: string, code: string): { stdout: string; stderr: string; status: number | null } {
  if (runtime === 'lua54') {
    const r = spawnSync('python3', [LUA_RUNNER], { input: code, encoding: 'utf-8' });
    return { stdout: r.stdout, stderr: r.stderr, status: r.status };
  }
  const dir = mkdtempSync(join(tmpdir(), 'qhaze-luau-'));
  const file = join(dir, 'example.luau');
  writeFileSync(file, code);
  const r = spawnSync(LUAU_RUNNER, [file], { encoding: 'utf-8' });
  return { stdout: r.stdout, stderr: r.stderr, status: r.status };
}

const examples = CONTENT_PACKAGES.flatMap((pkg) => collectCodeExamples(pkg));
const tools = { lua54: haveLua54(), luau: existsSync(LUAU_RUNNER) };
const results: Result[] = [];

describe('course-material code examples execute with the documented output', () => {
  it.each(examples.map((e) => [`${e.where} · ${e.id} (${e.runtime})`, e] as const))('%s', (_name, e) => {
    if (e.runtime === 'roblox') {
      results.push({ where: e.where, id: e.id, runtime: e.runtime, status: 'not-executed', detail: 'Roblox Studio only' });
      return;
    }
    if (!tools[e.runtime as 'lua54' | 'luau']) {
      results.push({ where: e.where, id: e.id, runtime: e.runtime, status: 'tool-missing' });
      return;
    }
    const r = run(e.runtime, e.code);
    const actual = r.stdout.replace(/\r\n/g, '\n').replace(/\n$/, '');
    const ok = r.status === 0 && actual === (e.expectedOutput ?? '');
    results.push({ where: e.where, id: e.id, runtime: e.runtime, status: ok ? 'passed' : 'failed', detail: ok ? undefined : `exit ${r.status}; stdout ${JSON.stringify(actual)}; stderr ${JSON.stringify(r.stderr.trim())}` });
    expect(r.stderr.trim(), `${e.id} stderr`).toBe('');
    expect(actual, `${e.id} output`).toBe(e.expectedOutput);
  });

  it('writes docs/CODE-VERIFICATION.md', () => {
    const counts = (s: Result['status']) => results.filter((r) => r.status === s).length;
    const lines = [
      '# Code example verification',
      '',
      `Generated by \`npm run verify:code\` on ${new Date().toISOString().slice(0, 10)}. Every code example in the`,
      'course-material packages was processed as follows:',
      '',
      '| Runtime | How it is verified |',
      '|---|---|',
      '| `lua54` | Executed with the official Lua 5.4 C interpreter (via `lupa`); stdout must match exactly |',
      '| `luau` | Executed with the official Luau VM (`tools/luau-runner`); stdout must match exactly. The type checker is not run |',
      '| `roblox` | **Not executed**: Roblox engine APIs exist only in Roblox Studio. The expected output is descriptive |',
      '',
      `**Summary:** ${counts('passed')} passed · ${counts('failed')} failed · ${counts('not-executed')} not executed (Roblox Studio only) · ${counts('tool-missing')} skipped (tool missing)`,
      '',
      '| Location | Example | Runtime | Result |',
      '|---|---|---|---|',
      ...results.map((r) => `| ${r.where} | \`${r.id}\` | ${r.runtime} | ${r.status === 'passed' ? '✅ passed' : r.status === 'failed' ? `❌ failed: ${r.detail}` : r.status === 'not-executed' ? '⚪ not executed (Roblox Studio only)' : '⚠️ tool missing'} |`),
      '',
    ];
    writeFileSync(join(ROOT, 'docs/CODE-VERIFICATION.md'), lines.join('\n'));
    expect(counts('failed')).toBe(0);
  });
});
